import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

/**
 * امضای دیجیتال انتشار افزونه‌ی وردپرس (CR-05)
 * ───────────────────────────────────────────────
 * مدل اعتماد: «ابر» (سرور خریدار) فقط پخش‌کننده است، نه مرجع اعتماد. هر انتشار افزونه با کلید خصوصی Ed25519
 * ناشر (که هرگز روی هیچ سرور ابری نیست) امضا می‌شود و کلید عمومی در کد افزونه «پین» شده است
 * (wordpress-plugin/emzagar-contracts/includes/class-emzagar-release.php). پس حتی اگر پاسخ ابر دستکاری شود،
 * یا ابر هک شود، افزونه‌ی نصب‌شده بسته‌ی بدون امضای معتبر ناشر را هرگز نصب نمی‌کند.
 *
 *   RELEASE.json  فهرست «همه‌ی» فایل‌های افزونه + SHA-256 هرکدام + نسخه (بایت‌های همین فایل امضا می‌شود)
 *   RELEASE.sig   emz-sig-v1 <keyId> <base64(Ed25519(RELEASE.json))>
 *
 * فایل emzagar-config.php (آدرس ابر) را ابر برای هر سایت می‌سازد و در امضا نیست؛ افزونه آن را فقط وقتی می‌پذیرد که
 * «دقیقاً» برابر قالب ثابتِ renderPluginConfig با آدرس ابرِ شناخته‌شده‌ی خودش باشد — هیچ کد PHP دلخواهی از آن نمی‌گذرد.
 */
export const RELEASE_MANIFEST = "RELEASE.json";
export const RELEASE_SIG = "RELEASE.sig";
export const PLUGIN_CONFIG = "emzagar-config.php";
export const RELEASE_SCHEMA = 1;
export const PLUGIN_SLUG = "emzagar-contracts";
export const PLUGIN_ROOT = path.join(process.cwd(), "wordpress-plugin", PLUGIN_SLUG);
const PHP_RELEASE_CLASS = "includes/class-emzagar-release.php";

export type TrustedKeys = Record<string, string>; // keyId → base64 (۳۲ بایت خام Ed25519)

export interface ReleaseManifest {
  schema: number;
  product: string;
  slug: string;
  version: string;
  issuedAt: string;
  files: Record<string, string>;
}

/** قالب ثابت و بایت‌به‌بایت emzagar-config.php؛ باید دقیقاً با Emzagar_Release::expected_config() یکی باشد */
export function renderPluginConfig(origin: string, pairing = ""): string {
  if (!/^https?:\/\/[A-Za-z0-9.\-:]+$/.test(origin)) throw new Error("invalid_cloud_origin");
  if (!/^[A-Za-z0-9_\-]*$/.test(pairing)) throw new Error("invalid_pairing");
  return `<?php\n// Generated by the Emzagar cloud — do not edit.\nif ( ! defined( 'ABSPATH' ) ) {\n\texit;\n}\nreturn array(\n\t'cloud_url' => '${origin}',\n\t'pairing'   => '${pairing}',\n);\n`;
}

const sha256hex = (b: Uint8Array) => crypto.createHash("sha256").update(b).digest("hex");

/** فایل‌های قابل امضا (همه‌ی فایل‌های افزونه به‌جز نقطه‌فایل‌ها، پیکربندی تولیدشده‌ی ابر و خود امضا) */
export function collectPluginFiles(dir = PLUGIN_ROOT, base = ""): Record<string, Uint8Array> {
  const out: Record<string, Uint8Array> = {};
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    if (e.name.startsWith(".")) continue;
    const rel = base ? `${base}/${e.name}` : e.name;
    if (!base && [PLUGIN_CONFIG, RELEASE_MANIFEST, RELEASE_SIG].includes(e.name)) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) Object.assign(out, collectPluginFiles(full, rel));
    else if (e.isFile()) out[rel] = new Uint8Array(fs.readFileSync(full));
  }
  return out;
}

export function buildManifest(files: Record<string, Uint8Array>, version: string, issuedAt = new Date().toISOString()): ReleaseManifest {
  const sorted: Record<string, string> = {};
  for (const k of Object.keys(files).sort()) sorted[k] = sha256hex(files[k]);
  return { schema: RELEASE_SCHEMA, product: PLUGIN_SLUG, slug: PLUGIN_SLUG, version, issuedAt, files: sorted };
}

/** کلید خام ۳۲ بایتی Ed25519 ← KeyObject عمومی */
export function publicKeyFromRaw(rawB64: string): crypto.KeyObject {
  const raw = Buffer.from(rawB64, "base64");
  if (raw.length !== 32) throw new Error("bad_public_key");
  const spkiPrefix = Buffer.from("302a300506032b6570032100", "hex");
  return crypto.createPublicKey({ key: Buffer.concat([spkiPrefix, raw]), format: "der", type: "spki" });
}

export function rawPublicKey(pub: crypto.KeyObject): string {
  const der = pub.export({ format: "der", type: "spki" }) as Buffer;
  return der.subarray(der.length - 32).toString("base64");
}

export function generateSigningKey(): { privatePem: string; publicRaw: string } {
  const { privateKey, publicKey } = crypto.generateKeyPairSync("ed25519");
  return { privatePem: privateKey.export({ format: "pem", type: "pkcs8" }).toString(), publicRaw: rawPublicKey(publicKey) };
}

export function signManifestBytes(manifestBytes: Uint8Array, privatePem: string, keyId: string): string {
  if (!/^[A-Za-z0-9._-]{3,64}$/.test(keyId)) throw new Error("bad_key_id");
  const sig = crypto.sign(null, manifestBytes, crypto.createPrivateKey(privatePem));
  return `emz-sig-v1 ${keyId} ${sig.toString("base64")}\n`;
}

/** کلیدهای پین‌شده را از همان فایل PHP افزونه می‌خواند (منبع حقیقت واحد) */
export function trustedKeysFromPhp(dir = PLUGIN_ROOT): TrustedKeys {
  const php = fs.readFileSync(path.join(dir, PHP_RELEASE_CLASS), "utf8");
  const body = /const\s+KEYS\s*=\s*array\(([\s\S]*?)\);/.exec(php)?.[1] ?? "";
  const keys: TrustedKeys = {};
  for (const m of body.matchAll(/'([A-Za-z0-9._-]+)'\s*=>\s*'([A-Za-z0-9+/=]{44})'/g)) keys[m[1]] = m[2];
  return keys;
}

/** نسخه‌ی هدر افزونه («Version: 2.3.0») */
export function headerVersion(php: string): string {
  return /^[ \t/*#@]*Version:[ \t]*(\d{1,4}\.\d{1,4}\.\d{1,4}(?:-[0-9A-Za-z.]{1,20})?)[ \t]*$/m.exec(php.slice(0, 8000))?.[1] ?? "";
}

export type VerifyResult = { ok: true; manifest: ReleaseManifest; keyId: string } | { ok: false; error: string };

export interface VerifyOptions {
  keys: TrustedKeys;
  /** نسخه‌ای که ابر اعلام کرده؛ اگر داده شود باید دقیقاً با نسخه‌ی امضاشده برابر باشد */
  expectVersion?: string;
  /** نسخه‌ی نصب‌شده؛ اگر داده شود فقط ارتقای «اکیداً جدیدتر» پذیرفته می‌شود (ضد بازگشت به نسخه‌ی آسیب‌پذیر) */
  currentVersion?: string;
  /** آدرس ابر؛ اگر داده شود emzagar-config.php (در صورت وجود) باید دقیقاً قالب ثابت باشد */
  cloudOrigin?: string;
}

function semverGt(a: string, b: string): boolean {
  const pa = a.split(/[.-]/).map((x) => parseInt(x, 10) || 0);
  const pb = b.split(/[.-]/).map((x) => parseInt(x, 10) || 0);
  for (let i = 0; i < 3; i++) if ((pa[i] ?? 0) !== (pb[i] ?? 0)) return (pa[i] ?? 0) > (pb[i] ?? 0);
  return false;
}

const SAFE_PATH = /^(?!.*(?:^|\/)\.\.?(?:\/|$))[A-Za-z0-9._-]+(?:\/[A-Za-z0-9._-]+)*$/;

/**
 * راستی‌آزمایی کامل یک بسته (نسخه‌ی مرجع Node؛ افزونه‌ی PHP همین قواعد را اجرا می‌کند):
 * امضای Ed25519 با کلید پین‌شده، نسخه، فهرست دقیق فایل‌ها و SHA-256 تک‌تک آن‌ها.
 * `entries`: مسیر نسبی (بدون پوشه‌ی slug) ← بایت‌های فایل.
 */
export function verifyRelease(entries: Record<string, Uint8Array>, opts: VerifyOptions): VerifyResult {
  const manifestBytes = entries[RELEASE_MANIFEST];
  const sigBytes = entries[RELEASE_SIG];
  if (!manifestBytes || !sigBytes) return { ok: false, error: "unsigned" };
  const m = /^emz-sig-v1 ([A-Za-z0-9._-]{3,64}) ([A-Za-z0-9+/]{86}==)\s*$/.exec(Buffer.from(sigBytes).toString("utf8"));
  if (!m) return { ok: false, error: "bad_signature_format" };
  const rawKey = opts.keys[m[1]];
  if (!rawKey) return { ok: false, error: "unknown_key" };
  let valid = false;
  try {
    valid = crypto.verify(null, manifestBytes, publicKeyFromRaw(rawKey), Buffer.from(m[2], "base64"));
  } catch {
    valid = false;
  }
  if (!valid) return { ok: false, error: "bad_signature" };

  let manifest: ReleaseManifest;
  try {
    manifest = JSON.parse(Buffer.from(manifestBytes).toString("utf8")) as ReleaseManifest;
  } catch {
    return { ok: false, error: "bad_manifest" };
  }
  if (manifest.schema !== RELEASE_SCHEMA || manifest.slug !== PLUGIN_SLUG || manifest.product !== PLUGIN_SLUG) return { ok: false, error: "wrong_product" };
  if (typeof manifest.version !== "string" || !/^\d{1,4}\.\d{1,4}\.\d{1,4}(-[0-9A-Za-z.]{1,20})?$/.test(manifest.version)) return { ok: false, error: "bad_version" };
  if (opts.expectVersion && manifest.version !== opts.expectVersion) return { ok: false, error: "version_mismatch" };
  if (opts.currentVersion && !semverGt(manifest.version, opts.currentVersion)) return { ok: false, error: "rollback" };
  if (!manifest.files || typeof manifest.files !== "object" || Array.isArray(manifest.files)) return { ok: false, error: "bad_manifest" };

  const expected = Object.keys(manifest.files);
  if (expected.length === 0 || expected.length > 2000) return { ok: false, error: "bad_manifest" };
  for (const p of expected) if (!SAFE_PATH.test(p) || !/^[0-9a-f]{64}$/.test(manifest.files[p])) return { ok: false, error: "bad_manifest" };

  const actual = Object.keys(entries).filter((p) => ![RELEASE_MANIFEST, RELEASE_SIG].includes(p));
  for (const p of actual) {
    if (p === PLUGIN_CONFIG) {
      if (opts.cloudOrigin) {
        let want = "";
        try {
          want = renderPluginConfig(opts.cloudOrigin);
        } catch {
          return { ok: false, error: "config_mismatch" };
        }
        if (Buffer.from(entries[p]).toString("utf8") !== want) return { ok: false, error: "config_mismatch" };
      }
      continue;
    }
    if (!(p in manifest.files)) return { ok: false, error: `unexpected_file:${p}` };
  }
  for (const p of expected) {
    if (!entries[p]) return { ok: false, error: `missing_file:${p}` };
    const a = Buffer.from(sha256hex(entries[p]));
    const b = Buffer.from(manifest.files[p]);
    if (!crypto.timingSafeEqual(a, b)) return { ok: false, error: `hash_mismatch:${p}` };
  }
  return { ok: true, manifest, keyId: m[1] };
}

/** پوشه‌ی افزونه‌ی همراه ابر: آیا امضای ناشر با فایل‌های فعلی می‌خواند؟ (۶۰ ثانیه کش) */
let bundledCache: { at: number; res: VerifyResult } | null = null;
export function verifyBundledRelease(dir = PLUGIN_ROOT, keys?: TrustedKeys): VerifyResult {
  const useCache = dir === PLUGIN_ROOT && !keys;
  if (useCache && bundledCache && Date.now() - bundledCache.at < 60_000) return bundledCache.res;
  let res: VerifyResult;
  try {
    const entries = collectPluginFiles(dir);
    for (const f of [RELEASE_MANIFEST, RELEASE_SIG]) {
      const p = path.join(dir, f);
      if (fs.existsSync(p)) entries[f] = new Uint8Array(fs.readFileSync(p));
    }
    res = verifyRelease(entries, { keys: keys ?? trustedKeysFromPhp(dir) });
  } catch {
    res = { ok: false, error: "unreadable" };
  }
  if (useCache) bundledCache = { at: Date.now(), res };
  return res;
}
