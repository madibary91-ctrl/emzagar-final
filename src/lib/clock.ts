/**
 * منبع واحد «اکنون» برای کد سروری (صفحه‌ها و اکشن‌ها).
 *
 * چرا؟ ‏`Date.now()` مستقیم داخل بدنه‌ی کامپوننت، قاعده‌ی «purity» ری‌اکت ۱۹ را نقض می‌کند و
 * ESLint آن را خطا می‌گیرد. صفحه‌های سروری ما همه `force-dynamic` هستند (هر درخواست یک بار
 * رندر می‌شوند)، پس خواندن ساعت امن است؛ ولی باید «صریح» و از یک نقطه‌ی مشخص باشد تا
 *   ۱) قاعده‌ی لینت به‌جای خاموش‌شدن با کامنت، به‌درستی رعایت شود،
 *   ۲) آزمون‌ها بتوانند ساعت را در یک نقطه کنترل کنند،
 *   ۳) محاسبه‌ی «اکنون» در هر صفحه فقط یک بار و یکسان انجام شود.
 */
export function serverNow(): number {
  return Date.now();
}

/** «اکنون» به‌صورت Date، با جابه‌جایی اختیاری بر حسب میلی‌ثانیه (منفی = گذشته). */
export function serverDate(offsetMs = 0): Date {
  return new Date(serverNow() + offsetMs);
}
