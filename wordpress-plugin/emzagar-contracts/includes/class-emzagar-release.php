<?php
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * راستی‌آزمایی انتشار افزونه با امضای دیجیتال ناشر (CR-05).
 *
 * مدل اعتماد: «ابر» فقط بسته را پخش می‌کند و مرجع اعتماد نیست. هر انتشار با کلید خصوصی Ed25519 ناشر امضا می‌شود
 * (RELEASE.json + RELEASE.sig؛ کلید خصوصی هرگز روی هیچ سروری نیست) و کلیدهای عمومی زیر در همین کد «پین» شده‌اند.
 * بنابراین اگر پاسخ ابر دستکاری شود، مهاجم میان‌راهی بسته را عوض کند یا ابر هک شود، افزونه‌ی نصب‌شده
 * بسته‌ای را که امضای معتبر ناشر ندارد هرگز نصب نمی‌کند (امضا + SHA-256 تک‌تک فایل‌ها + ضد بازگشت به نسخه‌ی قدیمی).
 *
 * قواعد (باید با src/lib/wp-release.ts → verifyRelease یکی باشد):
 *   ۱. RELEASE.sig = «emz-sig-v1 <keyId> <base64 امضا>» و باید با یکی از کلیدهای پین‌شده روی «بایت‌های» RELEASE.json درست باشد.
 *   ۲. RELEASE.json: schema=1، slug درست، نسخه‌ی معتبر، فهرست فایل‌ها با SHA-256.
 *   ۳. مجموعه‌ی فایل‌های بسته «دقیقاً» برابر فهرست امضاشده است: فایل اضافه، فایل گم‌شده، هش ناهمخوان، لینک نمادین،
 *      مسیر مشکوک (.. / مطلق / \) یا حجم غیرعادی ← رد.
 *   ۴. نسخه‌ی امضاشده باید اکیداً جدیدتر از نسخه‌ی نصب‌شده باشد (و اگر ابر نسخه‌ای اعلام کرده، با آن برابر).
 *   ۵. تنها استثنا emzagar-config.php است که ابر برای هر سایت می‌سازد: فقط وقتی پذیرفته می‌شود که «بایت‌به‌بایت» برابر
 *      قالب ثابت expected_config() با آدرس ابرِ شناخته‌شده‌ی خود افزونه باشد؛ پس هیچ کد PHP دلخواهی از آن نمی‌گذرد.
 *
 * بررسی دو بار انجام می‌شود: روی فایل zip پیش از استخراج (verify_zip) و روی پوشه‌ی استخراج‌شده درست پیش از جایگزینی
 * افزونه (verify_dir)؛ بررسی دوم از هر مسیر دانلودی (حتی آدرس بسته‌ی جعلی) عبور اجباری است.
 *
 * ناشر: کلید خصوصی را آفلاین نگه می‌دارد و با `npm run plugin:sign` امضا می‌کند. کلید «standby» برای چرخش اضطراری کلید است.
 */
final class Emzagar_Release {

	const SLUG        = 'emzagar-contracts';
	const MANIFEST    = 'RELEASE.json';
	const SIGNATURE   = 'RELEASE.sig';
	const CONFIG      = 'emzagar-config.php';
	const MAX_FILES   = 2000;
	const MAX_TOTAL   = 52428800; // ۵۰ مگابایت، حجم بازشده
	const MAX_SMALL   = 262144;   // سقف خواندن RELEASE.json

	/** کلیدهای عمومی پین‌شده‌ی ناشر (۳۲ بایت خام Ed25519، base64). */
	const KEYS = array(
		'emz-rel-2026-a'       => 'ZGEjhR54/LZValgQ2ncTm6u0GIrk9FxEqVlKthk40ww=',
		'emz-rel-2026-standby' => 'Ka6hJZ6jk6Y5gyEv1HQLerxKFm4lBJR95M7F4ZTdzlw=',
	);

	private static function err( $code, $msg ) {
		return new WP_Error( 'emzagar_release_' . $code, $msg );
	}

	/** مسیر نسبی امن: بدون «..»، بدون مسیر مطلق، بدون \ و نویسه‌ی عجیب */
	public static function safe_rel( $p ) {
		if ( ! is_string( $p ) || '' === $p || strlen( $p ) > 200 ) {
			return false;
		}
		if ( preg_match( '#(^|/)\.\.?(/|$)#', $p ) ) {
			return false;
		}
		return 1 === preg_match( '#^[A-Za-z0-9._\-]+(?:/[A-Za-z0-9._\-]+)*$#', $p );
	}

	/** محتوای دقیق emzagar-config.php؛ باید بایت‌به‌بایت با renderPluginConfig در src/lib/wp-release.ts یکی باشد */
	public static function expected_config( $cloud_url ) {
		if ( ! is_string( $cloud_url ) || 1 !== preg_match( '#^https?://[A-Za-z0-9.\-:]+$#', $cloud_url ) ) {
			return '';
		}
		return "<?php\n// Generated by the Emzagar cloud — do not edit.\nif ( ! defined( 'ABSPATH' ) ) {\n\texit;\n}\nreturn array(\n\t'cloud_url' => '" . $cloud_url . "',\n\t'pairing'   => '',\n);\n";
	}

	/** @return array{key:string,sig:string}|null */
	public static function parse_signature( $text ) {
		if ( 1 !== preg_match( '/^emz-sig-v1 ([A-Za-z0-9._-]{3,64}) ([A-Za-z0-9+\/]{86}==)\s*$/', (string) $text, $m ) ) {
			return null;
		}
		$raw = base64_decode( $m[2], true );
		if ( false === $raw || 64 !== strlen( $raw ) ) {
			return null;
		}
		return array(
			'key' => $m[1],
			'sig' => $raw,
		);
	}

	/** امضای Ed25519 روی بایت‌های RELEASE.json با یکی از کلیدهای پین‌شده */
	public static function verify_signature( $manifest_bytes, $sig_text, $keys = null ) {
		$keys = is_array( $keys ) ? $keys : self::KEYS;
		if ( ! function_exists( 'sodium_crypto_sign_verify_detached' ) ) {
			return self::err( 'nosodium', __( 'کتابخانه‌ی رمزنگاری (sodium) در این هاست در دسترس نیست؛ برای امنیت، به‌روزرسانی انجام نشد.', 'emzagar' ) );
		}
		$p = self::parse_signature( $sig_text );
		if ( null === $p ) {
			return self::err( 'sig_format', __( 'امضای بسته‌ی به‌روزرسانی ناخوانا است؛ نسخه‌ی فعلی دست‌نخورده ماند.', 'emzagar' ) );
		}
		if ( ! isset( $keys[ $p['key'] ] ) ) {
			return self::err( 'unknown_key', __( 'بسته با کلیدی امضا شده که ناشر افزونه نیست؛ رد شد.', 'emzagar' ) );
		}
		$pk = base64_decode( (string) $keys[ $p['key'] ], true );
		if ( false === $pk || 32 !== strlen( $pk ) ) {
			return self::err( 'bad_key', __( 'کلید پین‌شده‌ی افزونه نامعتبر است.', 'emzagar' ) );
		}
		try {
			$ok = sodium_crypto_sign_verify_detached( $p['sig'], (string) $manifest_bytes, $pk );
		} catch ( \Throwable $e ) { // phpcs:ignore PHPCompatibility.Keywords.NewKeywords.t_throwableFound
			unset( $e );
			$ok = false;
		}
		if ( ! $ok ) {
			return self::err( 'bad_signature', __( 'امضای دیجیتال بسته‌ی به‌روزرسانی معتبر نیست؛ احتمال دستکاری. نسخه‌ی فعلی دست‌نخورده ماند.', 'emzagar' ) );
		}
		return $p['key'];
	}

	/** پردازش RELEASE.json (فقط پس از تأیید امضا) */
	public static function parse_manifest( $bytes, $expect_version, $current_version ) {
		$m = json_decode( (string) $bytes, true );
		if ( ! is_array( $m ) || ! isset( $m['schema'], $m['slug'], $m['product'], $m['version'], $m['files'] ) || ! is_array( $m['files'] ) ) {
			return self::err( 'bad_manifest', __( 'فهرست امضاشده‌ی بسته خراب است.', 'emzagar' ) );
		}
		if ( 1 !== $m['schema'] || self::SLUG !== $m['slug'] || self::SLUG !== $m['product'] ) {
			return self::err( 'wrong_product', __( 'بسته متعلق به این افزونه نیست.', 'emzagar' ) );
		}
		if ( ! is_string( $m['version'] ) || 1 !== preg_match( '/^\d{1,4}\.\d{1,4}\.\d{1,4}(-[0-9A-Za-z.]{1,20})?$/', $m['version'] ) ) {
			return self::err( 'bad_version', __( 'نسخه‌ی بسته نامعتبر است.', 'emzagar' ) );
		}
		if ( '' !== $expect_version && $m['version'] !== $expect_version ) {
			return self::err( 'version_mismatch', __( 'نسخه‌ی بسته با نسخه‌ی اعلام‌شده یکی نیست؛ رد شد. دوباره بررسی کنید.', 'emzagar' ) );
		}
		if ( '' !== $current_version && ! version_compare( $m['version'], $current_version, '>' ) ) {
			return self::err( 'rollback', __( 'بسته جدیدتر از نسخه‌ی نصب‌شده نیست؛ از بازگشت به نسخه‌ی قدیمی جلوگیری شد.', 'emzagar' ) );
		}
		$n = count( $m['files'] );
		if ( $n < 1 || $n > self::MAX_FILES ) {
			return self::err( 'bad_manifest', __( 'فهرست امضاشده‌ی بسته خراب است.', 'emzagar' ) );
		}
		foreach ( $m['files'] as $rel => $hash ) {
			if ( ! self::safe_rel( (string) $rel ) || ! is_string( $hash ) || 1 !== preg_match( '/^[0-9a-f]{64}$/', $hash ) ) {
				return self::err( 'bad_manifest', __( 'فهرست امضاشده‌ی بسته خراب است.', 'emzagar' ) );
			}
		}
		return $m;
	}

	/**
	 * مقایسه‌ی دقیق فایل‌های بسته با فهرست امضاشده.
	 *
	 * @param array       $manifest    خروجی parse_manifest
	 * @param array       $hashes      مسیر نسبی ← SHA-256 (بدون RELEASE.json/RELEASE.sig/emzagar-config.php)
	 * @param string|null $config      محتوای emzagar-config.php در بسته (یا null اگر نیست)
	 * @param array       $origins     آدرس‌های ابرِ مجازِ شناخته‌شده برای قالب config
	 */
	public static function match_files( $manifest, $hashes, $config, $origins ) {
		foreach ( $hashes as $rel => $h ) {
			if ( ! isset( $manifest['files'][ $rel ] ) ) {
				/* translators: %s: file path */
				return self::err( 'unexpected_file', sprintf( __( 'فایل ناشناخته در بسته: %s', 'emzagar' ), (string) $rel ) );
			}
		}
		foreach ( $manifest['files'] as $rel => $h ) {
			if ( ! isset( $hashes[ $rel ] ) ) {
				/* translators: %s: file path */
				return self::err( 'missing_file', sprintf( __( 'فایل لازم در بسته نیست: %s', 'emzagar' ), (string) $rel ) );
			}
			if ( ! hash_equals( (string) $h, (string) $hashes[ $rel ] ) ) {
				/* translators: %s: file path */
				return self::err( 'hash_mismatch', sprintf( __( 'محتوای فایل با امضای ناشر نمی‌خواند (دستکاری): %s', 'emzagar' ), (string) $rel ) );
			}
		}
		if ( null !== $config ) {
			$ok = false;
			foreach ( (array) $origins as $o ) {
				$exp = self::expected_config( (string) $o );
				if ( '' !== $exp && hash_equals( $exp, (string) $config ) ) {
					$ok = true;
					break;
				}
			}
			if ( ! $ok ) {
				return self::err( 'config_mismatch', __( 'فایل پیکربندی بسته با قالب ثابت و آدرس ابر شما نمی‌خواند؛ رد شد.', 'emzagar' ) );
			}
		}
		return true;
	}

	/** مراحل مشترک پس از جمع‌آوری محتوا */
	private static function verify_parts( $manifest_bytes, $sig_text, $hashes, $config, $expect_version, $current_version, $origins, $keys ) {
		if ( null === $manifest_bytes || null === $sig_text ) {
			return self::err( 'unsigned', __( 'بسته امضای دیجیتال ناشر را ندارد؛ نصب نشد.', 'emzagar' ) );
		}
		$key = self::verify_signature( $manifest_bytes, $sig_text, $keys );
		if ( is_wp_error( $key ) ) {
			return $key;
		}
		$manifest = self::parse_manifest( $manifest_bytes, (string) $expect_version, (string) $current_version );
		if ( is_wp_error( $manifest ) ) {
			return $manifest;
		}
		$m = self::match_files( $manifest, $hashes, $config, $origins );
		if ( is_wp_error( $m ) ) {
			return $m;
		}
		return $manifest;
	}

	/** خواندن امن یک جریان تا سقف مشخص؛ در صورت بیشتر بودن false */
	private static function read_limited( $fh, $limit ) {
		$out = '';
		while ( ! feof( $fh ) ) {
			$chunk = fread( $fh, 65536 ); // phpcs:ignore WordPress.WP.AlternativeFunctions
			if ( false === $chunk ) {
				return false;
			}
			$out .= $chunk;
			if ( strlen( $out ) > $limit ) {
				return false;
			}
		}
		return $out;
	}

	/**
	 * بررسی فایل zip پیش از استخراج.
	 *
	 * @return array|WP_Error مانیفست تأییدشده یا خطا
	 */
	public static function verify_zip( $zip_path, $expect_version, $current_version, $origins, $keys = null ) {
		if ( ! class_exists( 'ZipArchive' ) ) {
			return self::err( 'nozip', __( 'ZipArchive در دسترس نیست.', 'emzagar' ) );
		}
		$z = new ZipArchive();
		if ( true !== $z->open( $zip_path ) ) {
			return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
		}
		$n = (int) $z->numFiles;
		if ( $n < 1 || $n > self::MAX_FILES + 20 ) {
			$z->close();
			return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
		}
		$prefix   = self::SLUG . '/';
		$hashes   = array();
		$total    = 0;
		$manifest = null;
		$sig      = null;
		$config   = null;
		for ( $i = 0; $i < $n; $i++ ) {
			$st   = $z->statIndex( $i );
			$name = is_array( $st ) && isset( $st['name'] ) ? (string) $st['name'] : '';
			if ( '' === $name || false !== strpos( $name, "\0" ) || false !== strpos( $name, '\\' ) || 0 !== strpos( $name, $prefix ) ) {
				$z->close();
				return self::err( 'bad_path', __( 'مسیر فایل در بسته مشکوک است؛ رد شد.', 'emzagar' ) );
			}
			$rel = substr( $name, strlen( $prefix ) );
			if ( '' === $rel ) {
				continue; // خود پوشه‌ی ریشه
			}
			if ( '/' === substr( $name, -1 ) ) {
				if ( ! self::safe_rel( rtrim( $rel, '/' ) ) ) {
					$z->close();
					return self::err( 'bad_path', __( 'مسیر فایل در بسته مشکوک است؛ رد شد.', 'emzagar' ) );
				}
				continue;
			}
			if ( ! self::safe_rel( $rel ) ) {
				$z->close();
				return self::err( 'bad_path', __( 'مسیر فایل در بسته مشکوک است؛ رد شد.', 'emzagar' ) );
			}
			$opsys = 0;
			$attr  = 0;
			if ( $z->getExternalAttributesIndex( $i, $opsys, $attr ) && ZipArchive::OPSYS_UNIX === $opsys && ( ( $attr >> 16 ) & 0170000 ) === 0120000 ) {
				$z->close();
				return self::err( 'symlink', __( 'بسته شامل لینک نمادین است؛ رد شد.', 'emzagar' ) );
			}
			$size   = (int) $st['size'];
			$total += $size;
			if ( $total > self::MAX_TOTAL || isset( $hashes[ $rel ] ) || self::MANIFEST === $rel && null !== $manifest || self::SIGNATURE === $rel && null !== $sig || self::CONFIG === $rel && null !== $config ) {
				$z->close();
				return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
			}
			$fh = $z->getStream( $name );
			if ( ! $fh ) {
				$z->close();
				return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
			}
			if ( self::MANIFEST === $rel || self::SIGNATURE === $rel || self::CONFIG === $rel ) {
				$data = self::read_limited( $fh, self::MAX_SMALL );
				fclose( $fh ); // phpcs:ignore WordPress.WP.AlternativeFunctions
				if ( false === $data ) {
					$z->close();
					return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
				}
				if ( self::MANIFEST === $rel ) {
					$manifest = $data;
				} elseif ( self::SIGNATURE === $rel ) {
					$sig = $data;
				} else {
					$config = $data;
				}
				continue;
			}
			$ctx  = hash_init( 'sha256' );
			$read = 0;
			while ( ! feof( $fh ) ) {
				$chunk = fread( $fh, 65536 ); // phpcs:ignore WordPress.WP.AlternativeFunctions
				if ( false === $chunk ) {
					break;
				}
				$read += strlen( $chunk );
				if ( $read > $size ) {
					break;
				}
				hash_update( $ctx, $chunk );
			}
			fclose( $fh ); // phpcs:ignore WordPress.WP.AlternativeFunctions
			if ( $read !== $size ) {
				$z->close();
				return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
			}
			$hashes[ $rel ] = hash_final( $ctx );
		}
		$z->close();
		return self::verify_parts( $manifest, $sig, $hashes, $config, $expect_version, $current_version, $origins, $keys );
	}

	/**
	 * بررسی پوشه‌ی استخراج‌شده (درست پیش از جایگزینی افزونه).
	 *
	 * @return array|WP_Error
	 */
	public static function verify_dir( $dir, $expect_version, $current_version, $origins, $keys = null ) {
		$dir = rtrim( (string) $dir, '/\\' );
		if ( '' === $dir || ! is_dir( $dir ) ) {
			return self::err( 'bad_dir', __( 'پوشه‌ی به‌روزرسانی پیدا نشد.', 'emzagar' ) );
		}
		$hashes   = array();
		$total    = 0;
		$count    = 0;
		$manifest = null;
		$sig      = null;
		$config   = null;
		try {
			$it = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $dir, FilesystemIterator::SKIP_DOTS ), RecursiveIteratorIterator::SELF_FIRST );
			foreach ( $it as $info ) {
				if ( $info->isLink() ) {
					return self::err( 'symlink', __( 'بسته شامل لینک نمادین است؛ رد شد.', 'emzagar' ) );
				}
				if ( $info->isDir() ) {
					continue;
				}
				$rel = str_replace( '\\', '/', substr( $info->getPathname(), strlen( $dir ) + 1 ) );
				if ( ! $info->isFile() || ! self::safe_rel( $rel ) ) {
					return self::err( 'bad_path', __( 'مسیر فایل در بسته مشکوک است؛ رد شد.', 'emzagar' ) );
				}
				++$count;
				$total += (int) $info->getSize();
				if ( $count > self::MAX_FILES + 20 || $total > self::MAX_TOTAL ) {
					return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
				}
				if ( self::MANIFEST === $rel || self::SIGNATURE === $rel || self::CONFIG === $rel ) {
					if ( (int) $info->getSize() > self::MAX_SMALL ) {
						return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
					}
					$data = file_get_contents( $info->getPathname() ); // phpcs:ignore WordPress.WP.AlternativeFunctions
					if ( false === $data ) {
						return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
					}
					if ( self::MANIFEST === $rel ) {
						$manifest = $data;
					} elseif ( self::SIGNATURE === $rel ) {
						$sig = $data;
					} else {
						$config = $data;
					}
					continue;
				}
				$h = hash_file( 'sha256', $info->getPathname() );
				if ( false === $h ) {
					return self::err( 'bad_zip', __( 'فایل به‌روزرسانی zip معتبر نیست.', 'emzagar' ) );
				}
				$hashes[ $rel ] = $h;
			}
		} catch ( \Throwable $e ) { // phpcs:ignore PHPCompatibility.Keywords.NewKeywords.t_throwableFound
			unset( $e );
			return self::err( 'bad_dir', __( 'پوشه‌ی به‌روزرسانی خوانده نشد.', 'emzagar' ) );
		}
		return self::verify_parts( $manifest, $sig, $hashes, $config, $expect_version, $current_version, $origins, $keys );
	}
}
